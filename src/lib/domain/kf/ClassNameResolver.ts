export const resolveZedData = (path: string): ClassNameResolver => {
	const parsed = path.split(".");
	if (parsed.length < 2) {
		return {
			name: "Unknown",
			image: "",
		};
	}

	const [packageName, className] = parsed;
	const data =
		zedData[
			className
				.split("Pawn_")[1]
				.replace("_Regular", "")
				.replace("_NRS", "")
				.replace("_RS", "")
		];
	return {
		name: data
			? data[0] +
				(packageName !== "kfgamecontent" && packageName !== "CombinedCD2"
					? ` (${packageName})`
					: "")
			: `Unknown (${path})`,
		image: data ? data[1] : "",
	};
};
