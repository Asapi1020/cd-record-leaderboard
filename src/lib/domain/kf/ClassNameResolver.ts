export interface ClassNameResolver {
	name: string;
	image: string;
}

export const resolveWeaponData = (path: string): ClassNameResolver => {
	const parsed = path.split(".");
	if (parsed.length < 2) {
		return {
			name: "Unknown",
			image: "",
		};
	}

	const [packageName, className] = parsed;
	const data = weaponData[className.split("Def_")[1]];
	return {
		name: data
			? data[0] + (packageName !== "KFGame" ? ` (${packageName})` : "")
			: `Unknown (${path})`,
		image: data ? data[1] : "",
	};
};

